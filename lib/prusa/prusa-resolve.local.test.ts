/**
 * Golden check against a real PrusaSlicer data folder:
 *
 *   PRUSASLICER_ROOT="$HOME/Library/Application Support/PrusaSlicer" vp test run lib/prusa/prusa-resolve.local.test.ts
 *
 * PrusaSlicer writes user presets as full snapshots, so every value the user
 * did not change is PrusaSlicer's own resolved parent value. Rebuilding a
 * file from our chain must therefore reproduce it line for line.
 */

import { readdirSync, readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';

import { describe, expect, it } from 'vite-plus/test';

import { buildMergedProfileData } from '@/lib/bambu/chain-display';
import type { InheritanceChainLevel } from '@/lib/bambu/resolver';

import { buildPrusaFullConfig, prusaLeafOverrides } from './prusa-leaf';
import {
  PRUSA_FILAMENT_OPTION_KEYS,
  PRUSA_PRINT_OPTION_KEYS,
  PRUSA_PROFILE_CONFIG_SOURCE,
} from './prusa-profile-config.generated';
import {
  parsePrusaValue,
  prusaKindForPath,
  serializePrusaValue,
  toPrusaDisplayChain,
} from './prusa-values';

type PrusaBundleModule = {
  loadVendorBundles(root: string): Promise<unknown[]>;
  resolvePrusaChain(
    root: string,
    relativePath: string,
    kind: 'print' | 'filament',
    bundles: unknown[],
  ): Promise<{ chain: InheritanceChainLevel[]; warnings: string[] }>;
  parseIni(text: string): { root: Record<string, string> };
  serializeUserPreset(values: Record<string, string>, header: string): string;
};

const prusaBundle = createRequire(import.meta.url)(
  '../../server/prusa-bundle.js',
) as PrusaBundleModule;

const root = process.env.PRUSASLICER_ROOT;

function userPresets(base: string): string[] {
  return ['print', 'filament'].flatMap((dir) => {
    try {
      return readdirSync(path.join(base, dir))
        .filter((name) => name.endsWith('.ini'))
        .map((name) => `${dir}/${name}`);
    } catch {
      return [];
    }
  });
}

function bodyLines(text: string): string[] {
  return text.split('\n').filter((line) => line !== '' && !line.startsWith('#'));
}

describe.skipIf(!root)('PrusaSlicer presets in PRUSASLICER_ROOT', () => {
  for (const relativePath of root ? userPresets(root) : []) {
    it(`rebuilds ${relativePath} exactly`, async () => {
      const bundles = await prusaBundle.loadVendorBundles(root!);
      const kind = prusaKindForPath(relativePath);
      const resolved = await prusaBundle.resolvePrusaChain(
        root!,
        relativePath,
        kind === 'filament' ? 'filament' : 'print',
        bundles,
      );
      expect(resolved.warnings).toEqual([]);
      const chain = toPrusaDisplayChain(kind, resolved.chain);
      const original = readFileSync(path.join(root!, relativePath), 'utf8');
      const rebuilt = prusaBundle.serializeUserPreset(
        buildPrusaFullConfig(chain, prusaLeafOverrides(chain)),
        '#',
      );
      const writtenByThisVersion = original.startsWith(
        `# generated by PrusaSlicer ${PRUSA_PROFILE_CONFIG_SOURCE.version.replace(/^version_/, '')} `,
      );
      if (writtenByThisVersion) {
        expect(bodyLines(rebuilt)).toEqual(bodyLines(original));
      } else {
        // An older PrusaSlicer wrote fewer options; every current one must survive.
        const keep = new Set(
          kind === 'filament' ? PRUSA_FILAMENT_OPTION_KEYS : PRUSA_PRINT_OPTION_KEYS,
        );
        const current = bodyLines(original).filter((line) => keep.has(line.split(' = ')[0]!));
        expect(bodyLines(rebuilt)).toEqual(expect.arrayContaining(current));
      }
    });

    it(`reports what ${relativePath} changes`, async () => {
      const bundles = await prusaBundle.loadVendorBundles(root!);
      const kind = prusaKindForPath(relativePath);
      const resolved = await prusaBundle.resolvePrusaChain(
        root!,
        relativePath,
        kind === 'filament' ? 'filament' : 'print',
        bundles,
      );
      const chain = toPrusaDisplayChain(kind, resolved.chain);
      const parent = buildMergedProfileData(chain, chain.length - 2);
      const leaf = prusaBundle.parseIni(readFileSync(path.join(root!, relativePath), 'utf8')).root;
      const changed = Object.keys(leaf).filter(
        (key) =>
          key !== 'inherits' &&
          serializePrusaValue(key, parsePrusaValue(key, leaf[key]!)) !==
            serializePrusaValue(key, parent[key]),
      );
      // Printed for a human to compare with PrusaSlicer's "modified" markers.
      process.stdout.write(`${relativePath}: ${changed.join(', ') || '(none)'}\n`);
      expect(changed).toEqual(
        Object.keys(prusaLeafOverrides(chain)).filter((key) => key !== 'inherits'),
      );
    });
  }
});
