const TECHNICAL_TOKENS = new Set([
  '1',
  '2',
  '3',
  '4',
  'ams',
  'ec',
  'hrc',
  'id',
  'nc',
  'x',
  'xy',
  'z',
]);

function titleCase(text: string): string {
  return text.length > 0 ? text[0]!.toUpperCase() + text.slice(1) : text;
}

function humanizeEnglishKey(key: string): string {
  return titleCase(
    key
      .split('_')
      .map((word) => {
        const upper = word.toUpperCase();
        return ['AMS', 'HRC', 'ID', 'NC', 'XY', 'Z'].includes(upper) ? upper : word;
      })
      .join(' '),
  );
}

function humanizeNorwegianKey(key: string): string {
  return titleCase(
    key
      .split('_')
      .map((word) => NB_WORDS[word.toLowerCase()] ?? word.toUpperCase())
      .join(' '),
  );
}

export function hasCompleteNorwegianLabel(key: string): boolean {
  return (
    Object.prototype.hasOwnProperty.call(SPECIAL_NB_LABELS, key) ||
    key
      .toLowerCase()
      .split('_')
      .every(
        (word) =>
          Object.prototype.hasOwnProperty.call(NB_WORDS, word) || TECHNICAL_TOKENS.has(word),
      )
  );
}

// PrusaSlicer groups use the English page and option-group titles as fallback.
function layoutTitle(fallback: string, locale: AppLocale): string {
  return locale === 'nb' ? (PRUSA_LAYOUT_TITLES_NB[fallback] ?? fallback) : fallback;
}

export function localizedGroupLabel(id: string, fallback: string, locale: AppLocale): string {
  const labels = GROUP_LABELS[id];
  return labels?.[locale === 'nb' ? 1 : 0] ?? layoutTitle(fallback, locale);
}

export function localizedSubgroupLabel(id: string, fallback: string, locale: AppLocale): string {
  const labels = SUBGROUP_LABELS[id];
  return labels?.[locale === 'nb' ? 1 : 0] ?? layoutTitle(fallback, locale);
}

export function localizedPropertyLabel(
  key: string,
  englishFallback: string,
  locale: AppLocale,
  slicer?: SlicerSource,
): string {
  if (locale === 'en') {
    return englishFallback === key ? humanizeEnglishKey(key) : englishFallback;
  }
  if (SPECIAL_NB_LABELS[key]) return SPECIAL_NB_LABELS[key];
  // PrusaSlicer keeps Slic3r's names; Bambu's renamed key has the translation.
  const equivalent = slicer === 'prusa' ? PRUSA_EQUIVALENT_KEYS[key] : undefined;
  if (equivalent) return SPECIAL_NB_LABELS[equivalent] ?? humanizeNorwegianKey(equivalent);
  return humanizeNorwegianKey(key);
}

export function localizedBoolean(value: boolean, locale: AppLocale): string {
  if (locale === 'nb') return value ? 'Ja' : 'Nei';
  return value ? 'Yes' : 'No';
}

export function localizedEnumValue(value: string, locale: AppLocale): string {
  const entry = ENUM_VALUES[value.trim().toLowerCase()];
  return entry?.[locale === 'nb' ? 1 : 0] ?? value;
}
