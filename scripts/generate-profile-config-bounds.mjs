import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import prettier from "prettier";

/**
 * Extracts the option definitions Bambu Studio itself enforces (type, declared
 * min/max, enum values) from PrintConfig.cpp, so validation can use the real
 * limits instead of the range that happens to occur in shipped profiles.
 */
const DEFAULT_SOURCE_URL =
  "https://raw.githubusercontent.com/bambulab/BambuStudio/master/src/libslic3r/PrintConfig.cpp";

const outputPath = path.resolve("lib/bambu/profile-config-bounds.generated.ts");
const localSource = process.env.BAMBUSTUDIO_PRINTCONFIG;
const sourceUrl = process.env.BAMBUSTUDIO_PRINTCONFIG_URL ?? DEFAULT_SOURCE_URL;

async function loadSource() {
  if (localSource) {
    return {
      text: await readFile(localSource, "utf8"),
      origin: localSource,
    };
  }
  const response = await fetch(sourceUrl);
  if (!response.ok) {
    throw new Error(`Could not download ${sourceUrl}: ${response.status}`);
  }
  return { text: await response.text(), origin: sourceUrl };
}

const { text, origin } = await loadSource();

// `def->max = max_temp;` and friends need the file's own constants.
const constants = new Map();
for (const match of text.matchAll(
  /(?:static\s+)?const\s+(?:int|float|double)\s+(\w+)\s*=\s*(-?[\d.]+)f?\s*;/g,
)) {
  const value = Number(match[2]);
  if (Number.isFinite(value)) constants.set(match[1], value);
}

function numberFrom(raw) {
  const trimmed = raw.trim().replace(/f$/, "");
  if (/^-?(?:\d+\.?\d*|\.\d+)$/.test(trimmed)) return Number(trimmed);
  return constants.get(trimmed) ?? null;
}

const definitions = new Map();
const addPattern =
  /this->add(?:_nullable)?\(\s*"([A-Za-z0-9_]+)"\s*,\s*(co\w+)\s*\)/g;
const additions = [...text.matchAll(addPattern)];

for (const [index, match] of additions.entries()) {
  const key = match[1];
  const type = match[2];
  const blockStart = match.index + match[0].length;
  const blockEnd = additions[index + 1]?.index ?? text.length;
  const block = text.slice(blockStart, blockEnd);

  const definition = { type };
  const min = block.match(/def->min\s*=\s*([^;]+);/);
  const max = block.match(/def->max\s*=\s*([^;]+);/);
  const minValue = min ? numberFrom(min[1]) : null;
  const maxValue = max ? numberFrom(max[1]) : null;
  if (minValue !== null) definition.min = minValue;
  if (maxValue !== null) definition.max = maxValue;

  const enumValues = [
    ...block.matchAll(/enum_values\.(?:push_back|emplace_back)\("([^"]*)"\)/g),
  ].map((entry) => entry[1]);
  if (enumValues.length > 0) definition.enumValues = enumValues;

  // Later definitions of the same key (per-printer variants) refine the first.
  const existing = definitions.get(key);
  definitions.set(key, existing ? { ...existing, ...definition } : definition);
}

const sorted = Object.fromEntries(
  [...definitions.entries()].sort(([left], [right]) =>
    left.localeCompare(right),
  ),
);

const contents = await prettier.format(
  `/**\n * Generated by scripts/generate-profile-config-bounds.mjs.\n * Source: ${origin}; do not edit manually.\n *\n * Declared option types and limits from Bambu Studio, which are authoritative\n * in a way that ranges observed across shipped profiles are not.\n */\nexport type ProfileConfigDef = {\n  type: string;\n  min?: number;\n  max?: number;\n  enumValues?: readonly string[];\n};\n\nexport const PROFILE_CONFIG_DEFS: Readonly<Record<string, ProfileConfigDef>> = ${JSON.stringify(sorted, null, 2)};\n`,
  { parser: "typescript" },
);

await writeFile(outputPath, contents, "utf8");
console.log(
  `Generated ${outputPath} with ${definitions.size} option definitions from ${origin}.`,
);
